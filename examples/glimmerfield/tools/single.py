#!/usr/bin/env python3
"""Concatenate the logic bench (Game, Perf, Bench, BenchMain) into one .bas, for VMs that
can't run multi-file projects yet (AmigaOS 4, 2026-11-08). The draw path is left out
(--draw needs SoftCanvas.cls). usage: tools/single.py OUT.bas"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__)) + "/.."
out = ["' generated by examples/glimmerfield/tools/single.py - do not edit", "Option Explicit"]
for name in ["Game.bas", "Perf.bas", "Bench.bas", "BenchMain.bas"]:
    src = open(os.path.join(here, name)).read()
    src = re.sub(r"(?im)^Option Explicit\s*$", "", src)
    if name == "Bench.bas":
        src = src.replace("Dim cv As SoftCanvas", "Dim cv As Object")
        src = src.replace("Set cv = New SoftCanvas\n        InitRender", "Err.Raise 5, , \"--draw needs the project build\"")
        src = src.replace("DrawWorld cv", "cv.Refresh")
    out.append("' ---- " + name + "\n" + src)
open(sys.argv[1], "w").write("\n".join(out))
