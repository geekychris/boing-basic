#!/usr/bin/env python3
"""make_font.py - PbFont.bas from the amiga3d engine's 16 x 16 font (a3d_font16.h,
DejaVu Sans Mono Bold, Bitstream Vera licence): characters 32..126, 16 rows of
16 bits, bit 15 left.   python3 tools/make_font.py [path/to/a3d_font16.h]"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "..", "..", "amiga_mcp", "examples", "amiga3d", "a3d_font16.h")
rows = [[int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{4})", line)] for line in open(src) if line.strip().startswith("{ 0x")]
assert len(rows) == 95 and all(len(r) == 16 for r in rows)
out = ["' PbFont - the amiga3d engine's 16 x 16 font (DejaVu Sans Mono Bold, Bitstream Vera",
       "' licence), generated by tools/make_font.py: characters 32..126, 16 rows, bit 15 left,",
       "' the baseline on row 12.",
       "Option Explicit", "",
       "Public fontRow(0 To 1519) As Long             ' (char - 32) * 16 + row", "",
       "Public Sub FontInit()",
       "    Dim s As String, i As Long"]
for i in range(0, 95, 5):
    chunk = "".join("%04X" % v for r in rows[i:i + 5] for v in r)
    out.append('    s = s & "%s"' % chunk)
out += ["    For i = 0 To 1519",
        '        fontRow(i) = CLng("&H" & Mid$(s, i * 4 + 1, 4))',
        "    Next i", "End Sub", ""]
open(os.path.join(here, "..", "PbFont.bas"), "w").write("\n".join(out))
