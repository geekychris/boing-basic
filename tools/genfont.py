#!/usr/bin/env python3
"""Writes src/runtime/canvas_font.h: the Canvas control's 6x9 text font (ASCII 32..126),
rendered without antialiasing from a monospaced system font (default: macOS Monaco 9)."""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Monaco.ttf"
out = sys.argv[2] if len(sys.argv) > 2 else "src/runtime/canvas_font.h"
f = ImageFont.truetype(path, 9)
H, TOP = 9, 2          # rows 2..10 of the rendered cell: caps from 2, descenders to 10
glyphs = []
for c in range(32, 127):
    im = Image.new("1", (8, 12), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=1)
    rows = []
    for y in range(TOP, TOP + H):
        b = 0
        for x in range(6):
            if im.getpixel((x, y)):
                b |= 0x80 >> x
        rows.append(b)
    glyphs.append(rows)
with open(out, "w") as o:
    o.write("/* canvas_font.h - generated by tools/genfont.py: 6 x 9 cells, ASCII 32..126,\n"
            " * one byte per row, bit 7 = leftmost pixel. */\n")
    o.write("#define CV_FONT_W 6\n#define CV_FONT_H 9\n")
    o.write("static const unsigned char cv_font[95][9] = {\n")
    for c, rows in zip(range(32, 127), glyphs):
        o.write("    {%s},  /* %s */\n" % (",".join("0x%02x" % r for r in rows), repr(chr(c)) if c != 92 else "backslash"))
    o.write("};\n")
