#!/usr/bin/env python3
"""gallery.py - write docs/gallery.md from examples/*/gallery.toml and their screenshots.

    tools/gallery.py            write docs/gallery.md
    tools/gallery.py --check    exit 1 if docs/gallery.md is out of date, or an example has
                                no gallery.toml, or a screenshot is missing

Each example directory has a gallery.toml:

    title = "Glimmerfield"
    category = "game"            # game | app | example
    summary = "One line: what it is."
    shows = ["Canvas", "Audio/MOD"]   # what it shows off about Boing BASIC
    perf = "354-365 fps native, 88 VM, 75-79 JIT (m1, --bench 1000)"   # optional
    readme = "README.md"         # optional; default README.md when there is one
    order = 10                   # optional; lower first within its group, then by title

    [[shot]]
    file = "docs/guest-2x.png"   # relative to the example directory
    caption = "The bot playing wave 3"
    run = { project = "Glimmerfield.bbp", args = "--bench 4000", secs = 8 }   # optional:
                                 # how tools/gallery_shot.py captures it on the OS4 guest

The first shot is the thumbnail in the contact sheet. Examples without a gallery.toml are
listed at the end (and fail --check) so new ones are not forgotten.
"""
import os
import sys
import tomllib

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
EX = os.path.join(ROOT, "examples")
OUT = os.path.join(ROOT, "docs", "gallery.md")
GROUPS = [("game", "Games"), ("app", "Applications"), ("example", "Examples and tools")]
SKIP = {"common"}          # shared modules, not a program
THUMB_W, SHOT_W = 200, 560


def anchor(title):
    s = "".join(c.lower() if c.isalnum() else "-" if c in " -_" else "" for c in title)
    while "--" in s:
        s = s.replace("--", "-")
    return s.strip("-")


def load():
    entries, missing, problems = [], [], []
    for name in sorted(os.listdir(EX)):
        d = os.path.join(EX, name)
        if not os.path.isdir(d) or name in SKIP or name.startswith("."):
            continue
        f = os.path.join(d, "gallery.toml")
        if not os.path.exists(f):
            missing.append(name)
            continue
        with open(f, "rb") as fh:
            meta = tomllib.load(fh)
        meta["dir"] = name
        if meta.get("category") not in dict(GROUPS):
            problems.append("%s: category must be one of %s" % (name, ", ".join(k for k, _ in GROUPS)))
            meta["category"] = "example"
        readme = meta.get("readme", "README.md" if os.path.exists(os.path.join(d, "README.md")) else None)
        meta["readme"] = readme if readme and os.path.exists(os.path.join(d, readme)) else None
        shots = []
        for s in meta.get("shot", []):
            if os.path.exists(os.path.join(d, s["file"])):
                shots.append(s)
            else:
                problems.append("%s: screenshot %s is missing" % (name, s["file"]))
        meta["shots"] = shots
        entries.append(meta)
    return entries, missing, problems


def rel(meta, path):
    return os.path.relpath(os.path.normpath(os.path.join(EX, meta["dir"], path)), os.path.dirname(OUT))


def esc(s):
    return s.replace("|", "\\|")


def render(entries, missing):
    by = {k: sorted((e for e in entries if e["category"] == k),
                    key=lambda e: (e.get("order", 100), e["title"].lower())) for k, _ in GROUPS}
    n = {k: len(v) for k, v in by.items()}
    L = []
    L.append("# Boing BASIC gallery\n")
    L.append("<!-- Generated by tools/gallery.py from examples/*/gallery.toml: edit those, then run it. -->\n")
    L.append("Boing BASIC is a Visual Basic 6 style language for AmigaOS 4.1 (PowerPC). A program "
             "runs in the interpreter (a bytecode VM, with an optional PowerPC JIT) for a quick "
             "edit-run cycle, or is compiled to C and built with GCC into a native executable. "
             "Forms are designed in the [AmiForge](https://github.com/geekychris/amiforge) IDE; "
             "the runtime brings a Canvas for 2D graphics, Engine3D for filled 3D, a ProTracker "
             "player and sound effects through AHI, menus, dialogs and ReAction gadgets, an ARexx "
             "port, and `Declare` for calling any AmigaOS library. See the "
             "[README](../README.md) and the [design](DESIGN.md).\n")
    L.append("Everything below was written in Boing BASIC and runs on AmigaOS 4.1; the screenshots "
             "are from the QEMU sam460ex guest. %d games, %d applications and %d examples and tools.\n"
             % (n["game"], n["app"], n["example"]))
    # contact sheet
    for k, label in GROUPS:
        if not by[k]:
            continue
        L.append("**%s**\n" % label)
        L.append("<table>")
        row = []
        cols = 4
        items = by[k]
        for i, e in enumerate(items):
            img = ('<img src="%s" width="%d" alt="%s"><br>' % (rel(e, e["shots"][0]["file"]), THUMB_W, e["title"])
                   if e["shots"] else "")
            row.append('<td align="center" valign="bottom"><a href="#%s">%s%s</a></td>' % (anchor(e["title"]), img, e["title"]))
            if len(row) == cols or i == len(items) - 1:
                L.append("<tr>" + "".join(row) + "</tr>")
                row = []
        L.append("</table>\n")
    # sections
    for k, label in GROUPS:
        if not by[k]:
            continue
        L.append("## %s\n" % label)
        for e in by[k]:
            L.append("### %s\n" % e["title"])
            L.append("%s\n" % e["summary"].strip())
            if e.get("shows"):
                L.append("**Shows off:** %s\n" % ", ".join(e["shows"]))
            if e.get("perf"):
                L.append("**Performance:** %s\n" % e["perf"].strip())
            for s in e["shots"]:
                L.append('<img src="%s" width="%d" alt="%s">\n' % (rel(e, s["file"]), s.get("width", SHOT_W), esc(s.get("caption", e["title"]))))
                if s.get("caption"):
                    L.append("*%s*\n" % s["caption"].strip())
            links = []
            if e["readme"]:
                links.append("[README](%s)" % rel(e, e["readme"]))
            links.append("[source](../examples/%s/)" % e["dir"])
            L.append(" · ".join(links) + "\n")
    if missing:
        L.append("## Not in the gallery yet\n")
        L.append(", ".join("[%s](../examples/%s/)" % (m, m) for m in missing) + "\n")
    return "\n".join(L)


def main():
    entries, missing, problems = load()
    text = render(entries, missing)
    for p in problems:
        print("gallery:", p, file=sys.stderr)
    if missing:
        print("gallery: no gallery.toml in:", ", ".join(missing), file=sys.stderr)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("gallery: docs/gallery.md is out of date (run tools/gallery.py)", file=sys.stderr)
        return 1 if cur != text or missing or problems else 0
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote docs/gallery.md: %d programs" % len(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
