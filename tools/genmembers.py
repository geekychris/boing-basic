#!/usr/bin/env python3
"""genmembers.py [--check] - src/compiler/rtmembers.h from the runtime classes' member tables
(canvas.c + canvas_paint_impl.h, engine3d.c, audio.c): the names `boing members` lists for
AmiForge's completion. M_/MP_ ids are methods, P_ ids properties. --check: exit 1 if the
header is out of date (make test)."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = {"Canvas": ["src/runtime/canvas.c", "src/runtime/canvas_paint_impl.h"],
       "Engine3D": ["src/runtime/engine3d.c"], "Audio": ["src/runtime/audio.c"],
       "Http": ["src/runtime/http_obj.c"], "Dictionary": ["src/runtime/dict.c"],
       "StringBuilder": ["src/runtime/sbuilder.c"], "Socket": ["src/runtime/socket.c"],
       "RegExp": ["src/runtime/regexp.c"],
       "Csv": ["src/runtime/csv.c"],
       "Process": ["src/runtime/process.c"],
       "IniFile": ["src/runtime/ini.c"],
       "Logger": ["src/runtime/logger.c"],
       "XmlDocument": ["src/runtime/xml.c"],
       "XmlElement": ["src/runtime/xml.c:elem_tab"]}
OUT = os.path.join(ROOT, "src/compiler/rtmembers.h")

def members(path):
    path, _, table = path.partition(":")      # file.c:table reads that table instead of members[]
    s = open(os.path.join(ROOT, path)).read()
    out = []
    pat = r'\b%s\[\]\s*=\s*\{(.*?)\n\};' % table if table else r'(?:members|paint_members)\[\]\s*=\s*\{(.*?)\n\};'
    for m in re.finditer(pat, s, re.S):
        for name, mid in re.findall(r'\{\s*"([A-Za-z_][A-Za-z0-9_]*)"\s*,\s*([A-Z0-9_]+)\s*\}', m.group(1)):
            out.append((name, "property" if mid.startswith("P_") else "method"))
    return out

def generate():
    lines = ["/* rtmembers.h - generated by tools/genmembers.py from the runtime classes' member tables:",
             "   the members `boing members` lists (AmiForge completion). Do not edit. */",
             "static const struct { const char *cls, *name, *kind; } bb_rtmembers[] = {"]
    for cls in sorted(SRC):
        seen = {}
        for p in SRC[cls]:
            for name, kind in members(p):
                seen.setdefault(name.lower(), (name, kind))
        for key in sorted(seen):
            name, kind = seen[key]
            lines.append('    {"%s", "%s", "%s"},' % (cls, name, kind))
    lines += ["};", ""]
    return "\n".join(lines)

text = generate()
if "--check" in sys.argv:
    cur = open(OUT).read() if os.path.exists(OUT) else ""
    if cur != text:
        print("rtmembers.h is out of date: run tools/genmembers.py")
        sys.exit(1)
    print("rtmembers.h: up to date (%d members)" % text.count("\n    {"))
    sys.exit(0)
open(OUT, "w").write(text)
print("wrote", OUT, text.count("\n    {"), "members")
