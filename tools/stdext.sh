#!/bin/sh
# stdext.sh - the standard extensions linked into the stock `boing` interpreter (STD_EXTS in the
# Makefile and mk/os4.mk; docs/extensions.md). Each is DIR/NAME/NAME.c (or .cpp) + NAME.bbx.
#   stdext.sh glue NAME...           the glue C: bb_vm_ext_init() calls each bb_ext_init_NAME()
#   stdext.sh libs host|os4 DIR NAME...   the -l flags from the .bbx 'link' lines for that target
set -e
cmd=$1; shift
case $cmd in
glue)
    echo '/* generated by tools/stdext.sh: the standard extensions of this interpreter */'
    for n in "$@"; do echo "void bb_ext_init_$n(void);"; done
    echo 'void bb_vm_ext_init(void);'
    echo 'void bb_vm_ext_init(void)'
    echo '{'
    for n in "$@"; do echo "    bb_ext_init_$n();"; done
    echo '}' ;;
libs)
    t=$1; d=$2; shift 2
    for n in "$@"; do
        awk -v t="$t" '$1 == "link" { if (NF == 2) print "-l" $2; else if (NF == 3 && $2 == t) print "-l" $3 }' "$d/$n/$n.bbx"
    done | awk -v t="$t" '!seen[$0]++ && $0 != "-lm" && !(t == "os4" && $0 == "-lauto")' | tr '\n' ' ' ;;
*) echo "usage: stdext.sh glue NAME... | libs host|os4 DIR NAME..." >&2; exit 5 ;;
esac
